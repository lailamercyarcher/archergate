"""Verify path-safe local imports without touching private user media."""
import tempfile
import unittest
from pathlib import Path

from archergate.media import sha256
from archergate.studio.library import Library, ffmpeg


class PathSafeImportTest(unittest.TestCase):
    def test_unicode_spaces_and_comma_in_media_path(self):
        with tempfile.TemporaryDirectory(prefix="archergate-import-") as temporary:
            root = Path(temporary)
            source = root / "scene, lumière 01.mp4"
            ffmpeg("-f", "lavfi", "-i", "testsrc2=size=128x72:rate=24",
                   "-f", "lavfi", "-i", "sine=frequency=440:sample_rate=48000",
                   "-t", "1.5", "-c:v", "libx264", "-pix_fmt", "yuv420p",
                   "-c:a", "aac", str(source))
            original_hash = sha256(source)
            library = Library(root / "private-workspace")
            result = library.import_media(str(source), "Synthetic local test",
                                          "Generated by the test", profile="compact")
            self.assertEqual(result["sha256"], original_hash)
            self.assertEqual(sha256(source), original_hash)
            self.assertTrue((library.path("media", result["id"], "proxy.mp4")).is_file())
            self.assertEqual(result["name"], source.name)
            self.assertTrue(result["source"]["streams"].get("video"))
            self.assertTrue(result["source"]["streams"].get("audio"))

    def test_missing_file_has_no_asset_side_effect(self):
        with tempfile.TemporaryDirectory(prefix="archergate-import-") as temporary:
            root = Path(temporary)
            library = Library(root / "private-workspace")
            with self.assertRaises((OSError, ValueError)):
                library.import_media(str(root / "not available, é.mp4"),
                                     "Synthetic test", "Generated for test")
            self.assertEqual(library.search(), [])


if __name__ == "__main__":
    unittest.main()