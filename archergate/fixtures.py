"""Generate original, clearly labeled synthetic source material."""

from pathlib import Path
from tempfile import TemporaryDirectory

from .media import (
    ENCODE, FPS, HEIGHT, SAMPLE_RATE, WIDTH, ExperimentError, read_registry, register,
    run_tool, sha256, storage_path, workspace_lock,
)

FIXTURES = {
    "signal": ("SIGNAL", "0xb94632", 330),
    "transit": ("TRANSIT", "0x24634f", 440),
    "echo": ("ECHO", "0x305e9c", 550),
}
RIGHTS = "Generated by ArcherGate Experiment 001 using geometric shapes and synthesized tones. No third-party footage or recordings."


def slate(label, tone):
    # FFmpeg's libass filter lays out and animates the text in video coordinates.
    return rf"""[Script Info]
ScriptType: v4.00+
PlayResX: {WIDTH}
PlayResY: {HEIGHT}
[V4+ Styles]
Format: Name, Fontname, Fontsize, PrimaryColour, SecondaryColour, OutlineColour, BackColour, Bold, Italic, Underline, StrikeOut, ScaleX, ScaleY, Spacing, Angle, BorderStyle, Outline, Shadow, Alignment, MarginL, MarginR, MarginV, Encoding
Style: Slate,DejaVu Sans,24,&H00FFFFFF,&H00FFFFFF,&H00000000,&H00000000,-1,0,0,0,100,100,0,0,1,0,0,7,0,0,0,1
[Events]
Format: Layer, Start, End, Style, Name, MarginL, MarginR, MarginV, Effect, Text
Dialogue: 0,0:00:00.00,0:00:03.00,Slate,,0,0,0,,{{\pos(36,36)\fsp3}}SYNTHETIC SOURCE
Dialogue: 0,0:00:00.00,0:00:03.00,Slate,,0,0,0,,{{\pos(32,115)\fs86}}{label}
Dialogue: 0,0:00:00.00,0:00:03.00,Slate,,0,0,0,,{{\pos(36,246)}}{tone} Hz / ARCHERGATE 001
Dialogue: 0,0:00:00.00,0:00:03.00,Slate,,0,0,0,,{{\move(34,302,550,302)}}|----
"""


def generate_fixtures(workspace):
    for asset, (label, color, tone) in FIXTURES.items():
        provenance = f"ArcherGate synthetic fixture v1: {label} slate, animated scanline, {tone} Hz sine tone."
        with workspace_lock(workspace):
            path = storage_path(workspace, "sources", f"{asset}.mp4")
            if asset not in read_registry(workspace, allow_empty=True):
                path.parent.mkdir(exist_ok=True)
                with TemporaryDirectory(dir=path.parent) as temp:
                    staging = Path(temp) / "fixture.mp4"
                    (Path(temp) / "slate.ass").write_text(slate(label, tone), encoding="utf-8")
                    run_tool(
                        "ffmpeg", "-nostdin", "-hide_banner", "-v", "error", "-filter_threads", "1",
                        "-f", "lavfi", "-i", f"color=c={color}:s={WIDTH}x{HEIGHT}:r={FPS}:d=3",
                        "-f", "lavfi", "-i", f"sine=frequency={tone}:sample_rate={SAMPLE_RATE}:duration=3",
                        "-vf", "drawgrid=w=40:h=40:t=1:c=white@0.1,ass=slate.ass", *ENCODE, staging, cwd=temp,
                    )
                    if path.exists():
                        if not path.is_file() or sha256(path) != sha256(staging):
                            raise ExperimentError(f"Existing {asset} media differs from the synthetic fixture.")
                    else:
                        # Link creation fails if another writer has already created the source.
                        path.hardlink_to(staging)
        register(workspace, asset, provenance, RIGHTS)
